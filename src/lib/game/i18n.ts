export const LANG_META: { id: LangId; label: string; dir: "ltr" | "rtl" }[] = [
  { id: "en", label: "English", dir: "ltr" },
  { id: "ur", label: "اردو", dir: "rtl" },
  { id: "ru", label: "Roman Urdu", dir: "ltr" },
  { id: "hi", label: "हिन्दी", dir: "ltr" },
  { id: "ar", label: "العربية", dir: "rtl" },
  { id: "tr", label: "Türkçe", dir: "ltr" },
  { id: "es", label: "Español", dir: "ltr" },
  { id: "fr", label: "Français", dir: "ltr" },
  { id: "de", label: "Deutsch", dir: "ltr" },
  { id: "zh", label: "中文", dir: "ltr" },
  { id: "ja", label: "日本語", dir: "ltr" },
  { id: "bn", label: "বাংলা", dir: "ltr" },
];

export function t(lang: LangId, key: string): string {
  return TABLES[lang]?.[key] ?? EN[key] ?? key;
}

export function dirFor(lang: LangId): "ltr" | "rtl" {
  return LANG_META.find((l) => l.id === lang)?.dir ?? "ltr";
}

export function greetingKey(h = new Date().getHours()) {
  if (h < 5) return "greetingNight";
  if (h < 12) return "greetingDawn";
  if (h < 17) return "greetingDay";
  if (h < 21) return "greetingDusk";
  return "greetingNight";
}

export function detectLang(): LangId {
  if (typeof navigator === "undefined") return "en";
  const n = (navigator.language || "en").toLowerCase();
  if (n.startsWith("ur")) return "ur";
  if (n.startsWith("ar")) return "ar";
  if (n.startsWith("hi")) return "hi";
  if (n.startsWith("tr")) return "tr";
  if (n.startsWith("es")) return "es";
  if (n.startsWith("fr")) return "fr";
  if (n.startsWith("de")) return "de";
  if (n.startsWith("zh")) return "zh";
  if (n.startsWith("ja")) return "ja";
  if (n.startsWith("bn")) return "bn";
  return "en";
}
